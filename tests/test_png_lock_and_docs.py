"""Gaps left open by the PNG hash lock, the Node pin's docs and the colorama note.

Found by mutating PR #48 at 7f0d896. Each test names the change it exists to catch. Like the
other config tests these read plain text files; none of them touch the network.
"""

import importlib.metadata as metadata
import re

from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

from hardlyfunny.build import ROOT

README = (ROOT / "README.md").read_text(encoding="utf-8")
PNG_COMMAND = re.search(r'docker run [^`]*python:(\d+\.\d+) sh -c "[^"]*pip install[^"]*requirements-png\.txt[^"]*"', README)


def lock_entries(name):
    """[(package, version, marker or None, [hashes])] for a hash-locked file."""
    text = (ROOT / name).read_text(encoding="utf-8")
    entries = []
    for entry in re.split(r"\n(?=\S)", text):
        match = re.match(r"([A-Za-z0-9_.-]+)==([\w.!+-]+)(?: ; ([^\\\n]+?))? \\\n", entry.strip() + "\n")
        if match:
            hashes = re.findall(r"--hash=sha256:([0-9a-f]{64})", entry)
            entries.append((canonicalize_name(match.group(1)), match.group(2), match.group(3), hashes))
    return entries


def png_lock_python():
    header = (ROOT / "requirements-png.txt").read_text(encoding="utf-8").splitlines()[1]
    return re.search(r"--python-version (\d+\.\d+)", header).group(1)


def test_readme_png_command_runs_on_the_python_the_png_lock_was_resolved_for():
    # The lock is resolved for one interpreter and installed with --only-binary, so a
    # `python:3.14` image against a 3.13 lock has no pyoxipng wheel and the command fails.
    assert PNG_COMMAND, "README no longer has a docker command that installs requirements-png.txt"
    assert PNG_COMMAND.group(1) == png_lock_python(), (PNG_COMMAND.group(1), png_lock_python())


def test_png_lock_header_is_the_exact_command_that_produces_it():
    # test_ci_gate_and_locks.py checks this for the other two locks only.
    header = (ROOT / "requirements-png.txt").read_text(encoding="utf-8").splitlines()[:2]
    assert header[0] == "# This file was autogenerated by uv via the following command:", header
    expected = (
        "uv pip compile requirements-png.in -o requirements-png.txt -c requirements.txt "
        f"--generate-hashes --universal --python-version {png_lock_python()} --no-annotate"
    )
    assert header[1].removeprefix("#").strip() == expected
    assert expected in README, "README no longer documents the command that regenerates requirements-png.txt"
    assert (ROOT / "requirements-png.in").exists()


def test_png_lock_holds_every_production_pin_at_the_same_version():
    # requirements-png.in starts with `-r requirements.in`, so the lock must contain all of it.
    # The existing test only compares packages that happen to be in both files.
    prod = {package: version for package, version, _, _ in lock_entries("requirements.txt")}
    png = {package: version for package, version, _, _ in lock_entries("requirements-png.txt")}
    assert prod, "requirements.txt has no pins"
    assert {name: png.get(name) for name in prod} == prod


def test_png_lock_hashes_are_unique_per_package_and_every_entry_has_them():
    entries = lock_entries("requirements-png.txt")
    assert {"pyoxipng", "pillow"} <= {package for package, *_ in entries}
    for package, version, marker, hashes in entries:
        assert hashes, f"{package}=={version} has no hashes"
        assert len(hashes) == len(set(hashes)), f"{package}=={version} lists a hash twice"


def test_png_lock_is_closed_over_everything_installed_from_it():
    # Same check test_ci_gate_and_locks.py runs for the other locks, restricted to the packages
    # that exist in this environment (pyoxipng only installs in the Docker image).
    entries = lock_entries("requirements-png.txt")
    locked = {package for package, *_ in entries}
    checked = 0
    for package, version, marker, _ in entries:
        if marker and not Marker(marker).evaluate():
            continue
        try:
            dist = metadata.distribution(package)
        except metadata.PackageNotFoundError:
            continue
        checked += 1
        assert dist.version == version, f"{package}: installed {dist.version}, png lock has {version}"
        for requirement in map(Requirement, dist.requires or []):
            if requirement.marker is None or requirement.marker.evaluate({"extra": ""}):
                assert canonicalize_name(requirement.name) in locked, f"{package} needs {requirement.name}"
    assert checked >= 3, "expected Pillow, Jinja2 and MarkupSafe to be checked"


def test_readme_names_the_node_version_that_ci_installs():
    # `.node-version` moves on purpose, and the README quotes it. It named 24.22.3 until this PR.
    pinned = (ROOT / ".node-version").read_text(encoding="utf-8").strip()
    section = README.split("**Node.**", 1)[1].split("\n\n", 1)[0]
    assert f"`{pinned}`" in section, f"README's Node paragraph does not mention .node-version {pinned}"
    assert not (set(re.findall(r"`(\d+\.\d+\.\d+)`", section)) - {pinned}), "README quotes a different exact Node version"


def test_colorama_marker_in_the_lock_is_the_one_pytest_declares():
    # The note says colorama is Windows-only because pytest says so. If pytest ever needs it
    # everywhere, the lock's marker (and the README's reassurance) would be wrong.
    required = [Requirement(r) for r in metadata.requires("pytest") or [] if r.startswith("colorama")]
    assert len(required) == 1, required
    marker = required[0].marker
    assert marker is not None, "pytest now requires colorama on every platform"
    env = {"extra": ""}
    assert marker.evaluate({**env, "sys_platform": "win32"}) and not marker.evaluate({**env, "sys_platform": "linux"})
    lock = {package: marker for package, _, marker, _ in lock_entries("requirements-dev.txt")}
    assert Marker(lock["colorama"]).evaluate({"sys_platform": "win32"})
    assert not Marker(lock["colorama"]).evaluate({"sys_platform": "linux"})
    assert not Marker(lock["colorama"]).evaluate({"sys_platform": "darwin"})
